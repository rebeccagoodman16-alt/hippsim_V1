"""Population dynamics in Brian2: Brunel (2000) sparse excitatory–inhibitory network of leaky integrate-and-fire neurons.
Generated by hippsim (Neuron atlas → Simulate → Population). Point neurons: the reconstruction of {NAME} sets only the
membrane time constant here (τ = Rm·Cm = 20 ms, as in hippsim's passive check). Brunel N (2000) J Comput Neurosci 8:183–208.
Needs: pip install brian2 matplotlib. Try g (inhibition/excitation) 3–6 and nu_ext/nu_thr 0.9–4 for the four regimes."""
from brian2 import *
import matplotlib.pyplot as plt

N_E, N_I = 8000, 2000; eps = 0.1; C_E, C_I = int(eps*N_E), int(eps*N_I)
tau, theta, V_r, tau_rp, J, D = 20*ms, 20*mV, 10*mV, 2*ms, 0.1*mV, 1.5*ms
g, nu_ratio = {G_RATIO}, {NU_RATIO}          # from hippsim (Brunel 2000 Fig. 8: SR 3, 2 · SI fast 6, 4 · AI 5, 2 · SI slow 4.5, 0.9)
nu_thr = theta/(J*C_E*tau)
G = NeuronGroup(N_E + N_I, "dv/dt = -v/tau : volt (unless refractory)", threshold="v > theta", reset="v = V_r",
                refractory=tau_rp, method="exact")
G.v = "V_r + rand()*(theta - V_r)"
E, I = G[:N_E], G[N_E:]
SE = Synapses(E, G, on_pre="v += J", delay=D); SE.connect(p=eps)
SI = Synapses(I, G, on_pre="v += -g*J", delay=D); SI.connect(p=eps)
ext = PoissonInput(G, "v", C_E, nu_ratio*nu_thr, weight=J)
spk = SpikeMonitor(G[:50]); rate = PopulationRateMonitor(G)
run(300*ms)
print(f"mean rate {rate.smooth_rate(width=5*ms)[len(rate.t)//3:].mean()/Hz:.1f} Hz (g = {g}, nu_ext/nu_thr = {nu_ratio})")
fig, ax = plt.subplots(2, 1, sharex=True)
ax[0].plot(spk.t/ms, spk.i, ".k", ms=2); ax[0].set_ylabel("neuron")
ax[1].plot(rate.t/ms, rate.smooth_rate(width=1*ms)/Hz); ax[1].set_ylabel("rate (Hz)"); ax[1].set_xlabel("time (ms)")
plt.show()
