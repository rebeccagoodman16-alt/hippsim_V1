"""Citation files for the repository.

  references.bib   every paper the simulator's model cards and perturbations cite (46 verified references)
                   + morphologies/references.bib (sources of every reconstruction)
  CITATION.cff     how to cite hippsim itself (GitHub shows a "Cite this repository" button for it)
  python tools/citations.py
"""
from __future__ import annotations

import datetime
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEY_PAPERS = ["ceballos2025", "golomb2006", "lowet2023", "migliore2018", "magee1998", "hines1997", "ascoli2007"]


def bibtex(key: str, r: dict) -> str:
    vol, _, pages = (r.get("v") or "").partition(":")
    doi = r["u"].split("doi.org/")[1] if "doi.org/" in (r.get("u") or "") else ""
    f = {"author": " and ".join(a.strip() for a in r["a"].split(",")), "title": "{" + r["t"] + "}", "journal": r["j"],
         "year": r["y"], "volume": vol.strip(), "pages": pages.strip().replace("–", "--"), "doi": doi,
         "url": "" if doi else r.get("u", "")}
    return f"@article{{{key},\n" + ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items() if v) + "\n}"


def main() -> None:
    js = (ROOT / "site/hs-cards.js").read_text()
    refs = json.loads(subprocess.run(["node", "-e", "global.window={};" + js + ";process.stdout.write(JSON.stringify(window.HS_CARDS.refs))"],
                                     capture_output=True, text=True, check=True).stdout)
    head = ("% hippsim references. Generated by tools/citations.py from the simulator's model cards.\n"
            "% Morphology sources: morphologies/references.bib\n\n")
    (ROOT / "references.bib").write_text(head + "\n\n".join(bibtex(k, r) for k, r in sorted(refs.items())) + "\n")

    cff = [
        "cff-version: 1.2.0",
        'message: "If you use hippsim, please cite it as below, and cite the models and morphologies you used (references.bib, morphologies/references.bib)."',
        'title: "hippsim: lab simulator for hippocampal and cellular neuroscience"',
        "type: software",
        "authors:",
        "  - given-names: Rebecca",
        f"date-released: {datetime.date.today().isoformat()}",
        'version: "0.5.0"',
        "keywords: [computational neuroscience, hippocampus, CA1, NEURON, compartmental model, Alzheimer's disease]",
        "references:",
    ]
    for k in KEY_PAPERS:
        r = refs.get(k)
        if not r:
            continue
        doi = r["u"].split("doi.org/")[1] if "doi.org/" in (r.get("u") or "") else ""
        cff += ["  - type: article",
                "    authors:"] + [f'      - name: "{a.strip()}"' for a in r["a"].split(",")] + [
                f'    title: "{r["t"]}"', f'    journal: "{r["j"]}"', f"    year: {r['y']}"] + ([f"    doi: {doi}"] if doi else [])
    (ROOT / "CITATION.cff").write_text("\n".join(cff) + "\n")
    print(f"references.bib: {len(refs)} entries · CITATION.cff with {len(KEY_PAPERS)} key references")


if __name__ == "__main__":
    main()
